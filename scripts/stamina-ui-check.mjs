import assert from 'node:assert/strict'
import { createServer } from 'vite'
import vue from '@vitejs/plugin-vue'
import { createSSRApp } from 'vue'
import { renderToString } from '@vue/server-renderer'
import { fixture, add, enemy, select, settleAnimations, setBalls } from './item-test-helpers.mjs'
import { createMerchantEntity, merchantSellPrice } from '../src/game/data/merchants.js'

const server = await createServer({ configFile: false, plugins: [vue()], server: { middlewareMode: true, hmr: false, ws: false, watch: null }, optimizeDeps: { noDiscovery: true, include: [] }, appType: 'custom' })
try {
  const { default: Hud } = await server.ssrLoadModule('/src/ui/VueHud.vue')
  const run = fixture(), weapon = add(run, 'rust-sword'), potion = add(run, 'health-potion')
  const render = () => renderToString(createSSRApp(Hud, { run }))
  const endButton = html => html.match(/<button\b[^>]*data-action="end-turn"[^>]*>/)?.[0]
  const useButton = html => html.match(/<button\b[^>]*data-action="use"[^>]*>/)?.[0]
  const ballButtons = html => html.match(/<button\b[^>]*class="[^"]*stamina-ball[^>]*>/g) || []
  let html = await render()
  assert(!endButton(html)); assert(!useButton(html)); assert.equal(ballButtons(html).length, 0)
  assert(!html.includes('翻出敌人后抽球'))
  run.staminaDeck.draw(2)
  html = await render()
  assert.equal(ballButtons(html).length, 0, 'The HUD must hide residual balls outside combat')
  assert.equal(run.selectInventory(run.backpack.originIndex(run.backpack.placementOf(weapon.uid))), false)
  run._changed()
  assert.equal(run.player.energy, 0)
  run.showItemDetail(weapon)
  html = await render()
  assert(/class="(?=[^"]*stamina-ball-icon)(?=[^"]*scorch)[^"]*"/.test(html))
  assert(!html.includes('万能球可替代') && !html.includes('进入战斗后抽球') && !html.includes('💪'))
  const pet = add(run, 'mountain-hound')
  run.showItemDetail(pet)
  html = await render()
  assert(/class="(?=[^"]*stamina-ball-icon)(?=[^"]*wild)[^"]*"/.test(html))
  assert(!html.includes('占2格') && !html.includes('宠物不区分球属性'))
  assert.equal(run.detailPanel.description, '')
  const defense = add(run, 'light-armor')
  run.showItemDetail(defense)
  html = await render()
  const header = html.slice(html.indexOf('class="detail-head"'), html.indexOf('class="detail-badges"'))
  assert(header.includes('class="detail-armor"') && header.includes(`护甲 ${defense.armorValue}`))
  assert.equal(run.detailPanel.statLines.length, 0)
  assert.equal(run.detailPanel.effectLines.length, 0)
  assert.equal(run.detailPanel.description, '')
  assert(!html.includes('首次进入新房间时获得该护甲值'))
  assert(!html.includes('vital-energy-fill'))
  const merchant = createMerchantEntity('merchant', { c: 4, r: 3 })
  run.currentRoom.addEntity(merchant)
  assert(run._interactMerchant(merchant))
  const shopWeapon = add(run, 'bone-knife')
  const shopIndex = run.backpack.originIndex(run.backpack.placementOf(shopWeapon.uid))
  const sellButton = html => html.match(/<button\b[^>]*data-action="merchant-sell"[^>]*>/)?.[0]
  html = await render()
  assert(sellButton(html).includes('disabled'))
  assert(run.selectInventory(shopIndex))
  html = await render()
  assert(!sellButton(html).includes('disabled'), 'Selecting a shop weapon must enable selling without spirit fire')
  assert.equal(run.selectedItem, shopWeapon)
  assert(/class="(?=[^"]*\bhud-rest\b)(?=[^"]*\bshow\b)[^"]*"/.test(html))
  assert.equal(ballButtons(html).length, 0)
  const beforeSale = run.player.gold
  assert(run.sellSelectedMerchantItem())
  html = await render()
  assert.equal(run.player.gold, beforeSale + merchantSellPrice(shopWeapon))
  assert(sellButton(html).includes('disabled'))
  assert.equal(run.backpack.placementOf(shopWeapon.uid), null)
  assert(run.closeMerchant())
  run.currentRoom.removeEntity(merchant.id)
  const target = enemy(run)
  run._synchronizeBattle()
  html = await render()
  assert.equal(ballButtons(html).filter(button => button.includes('aria-pressed="true"')).length, 1)
  assert(ballButtons(html).at(-1).includes('aria-pressed="true"'))
  setBalls(run, 6, weapon.attribute)
  const weaponIndex = run.backpack.originIndex(run.backpack.placementOf(weapon.uid))
  assert(run.selectInventory(weaponIndex))
  html = await render()
  assert.equal(ballButtons(html).length, 6)
  assert(!html.includes('stamina-count'))
  const renderedBalls = html.match(/<button\b[^>]*class="[^"]*stamina-ball[^>]*>[\s\S]*?<\/button>/g) || []
  assert(renderedBalls.every(button => !button.replace(/<[^>]+>/g, '').trim()))
  assert(html.includes('--ball-slots:10'))
  assert(html.includes('原地攻击')); assert(html.includes('灵火池'))
  assert(/class="(?=[^"]*stamina-ball-icon)(?=[^"]*scorch)[^"]*"/.test(html))
  assert(!endButton(html).includes('disabled'))
  assert(!useButton(html))
  const id = run.staminaDeck.hand[0].id
  assert.equal(run.toggleStaminaBall(id), false)
  assert(ballButtons(html).every(button => button.includes('aria-disabled="true"')))
  assert(run.clearSelection())
  assert(run.toggleStaminaBall(id)); html = await render()
  assert.equal(ballButtons(html).filter(button => button.includes('aria-pressed="true"')).length, 1)
  assert(ballButtons(html).every(button => !button.includes('aria-disabled="true"')))
  weapon.energyCost = 3
  setBalls(run, 2, weapon.attribute)
  assert.equal(run.selectInventory(weaponIndex), false)
  html = await render()
  assert(!html.includes('原地攻击'), 'Unaffordable weapon clicks must not open a weapon selection')
  setBalls(run, 3, weapon.attribute)
  assert(run.selectInventory(weaponIndex)); html = await render()
  assert(!html.includes('体力球不足'))
  assert.equal(ballButtons(html).filter(button => button.includes('aria-pressed="true"')).length, 3)
  assert.equal((html.match(/class="stamina-selection-arc"/g) || []).length, 3)
  assert(!/伤害\d+%/.test(html))
  run.staminaDeck.pay(1, weapon.attribute, { selection: false })
  html = await render()
  assert.equal(run.selectedItem, null)
  assert(!html.includes('原地攻击'))
  assert(ballButtons(html).every(button => !button.includes('aria-disabled="true"')))
  setBalls(run, 3, weapon.attribute)
  assert(run.selectInventory(weaponIndex))
  run.staminaDeck.discardHand()
  run._changed()
  html = await render()
  assert.equal(run.selectedItem, null)
  assert(!html.includes('原地攻击')); assert(!endButton(html).includes('disabled'))
  select(run, potion); html = await render()
  assert(useButton(html).includes('disabled')); assert(!endButton(html))
  assert(run.selectInventory(run.selectedInventoryIndex)); html = await render()
  assert(!useButton(html)); assert(!endButton(html).includes('disabled'))
  assert(run.endPlayerTurn()); html = await render()
  assert(endButton(html).includes('disabled')); assert.equal(ballButtons(html).length, 0)
  settleAnimations(run); html = await render()
  assert.equal(ballButtons(html).length, 7)
  run._damageEnemy(target, 500); run._endTurn(); settleAnimations(run)
  html = await render(); assert(!endButton(html)); assert.equal(ballButtons(html).length, 0)
  assert(!html.includes('\ufffd'))
  console.log('stamina-ui-check passed: colored balls, selected payment, manual empty turn, pet/enemy lock, refill, decoded labels')
} finally { await server.close() }
