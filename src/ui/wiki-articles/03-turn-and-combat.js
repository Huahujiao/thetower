步痕靴和回身盾仅在攻击后紧接的第一个主动移动操作提供1层闪避、反击，持续至当次敌人阶段结束。闪避后不触发反击；同阶段另一场未闪避攻击仍可消耗反击。回身盾伤害取上一击武器攻击力（含固定增益，不含属性、地形和接力倍率）的一半向上取整。自动接近攻击的移动也可触发这些效果。

